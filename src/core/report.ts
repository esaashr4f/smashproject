// Plain-text / Markdown export, for pasting into Discord or a GitHub issue.
import type { Explanation, Finding } from './types';
import type { ScanReport } from './scanner/scan';
import { formatAddress } from './crashlog/match';

export const plural = (n: number, w: string) => `${n} ${w}${n === 1 ? '' : 's'}`;

const ICON = { error: '❌', warning: '⚠️', info: 'ℹ️', ok: '✅' } as const;

const finding = (f: Finding) => `- ${ICON[f.severity]} **${f.title}** (${f.confidence})\n  ${f.detail}${f.fix ? `\n  Fix: ${f.fix}` : ''}`;

export function explanationMarkdown(x: Explanation): string {
  const l = x.log;
  const lines = [`### ${x.best.title}`];
  if (l.fileName) lines.push(`File: \`${l.fileName}\``);
  if (l.isCrashReport) {
    if (l.timestamp) lines.push(`Time: ${l.timestamp.toISOString().replace('T', ' ').slice(0, 16)} UTC`);
    lines.push(`Game version: ${l.gameVersion ?? 'unknown'} · Result: ${l.result?.formatted ?? '?'} · ${l.exceptionType ?? ''}`);
    lines.push(`PC: \`${formatAddress(l.pc)}\`  LR: \`${formatAddress(l.lr)}\``);
    lines.push(`Loaded plugins: ${x.loadedPlugins.join(', ') || 'none'}`);
  }
  lines.push('', `Confidence: ${x.best.confidence}`, '', x.best.summary, '', 'Fix:', ...x.best.fix.map((f, i) => `${i + 1}. ${f}`));
  if (x.alsoPossible.length) lines.push('', 'Also possible: ' + x.alsoPossible.map((d) => d.title).join('; '));
  return lines.join('\n');
}

export function reportMarkdown(r: ScanReport): string {
  const out: string[] = ['## Smash Mod Doctor report', ''];
  out.push(`${plural(r.counts.error, 'error')}, ${plural(r.counts.warning, 'warning')}, ${r.counts.modsOk} of ${r.mods.length} mods OK.`, '');
  if (r.skipped.length) out.push('Not checked in this mode:', ...r.skipped.map((s) => `- ${s}`), '');
  if (r.base.items.length) {
    out.push('### Base setup');
    for (const i of r.base.items) out.push(`- ${ICON[i.status]} ${i.label}${i.version ? ` ${i.version}` : ''}${i.detail ? `: ${i.detail}` : ''}`);
    if (r.base.gameVersion) out.push(`- Game version (from ARCropolis cache): ${r.base.gameVersion}`);
    out.push('');
  }
  if (r.findings.length) out.push('### Findings', ...r.findings.map(finding), '');
  out.push('### Mods', '| Mod | Slots | Smashline | Status |', '|---|---|---|---|');
  for (const m of r.mods)
    out.push(`| ${m.name.replace(/\|/g, '\\|')}${m.disabled ? ' (disabled)' : ''} | ${m.slots || '-'} | ${m.moveset ? (m.moveset.needs === 'unchecked' ? 'not checked' : m.moveset.needs) : '-'} | ${ICON[m.status]} |`);
  if (r.matrix.versions.some((v) => v.works.length + v.breaks.length + v.unsure.length)) {
    out.push('', '### Smashline compatibility');
    for (const v of r.matrix.versions)
      out.push(`- With ${v.version}: ${v.works.length} work, ${v.breaks.length} break${v.breaks.length ? ` (${v.breaks.join(', ')})` : ''}, ${v.unsure.length} unsure${v.unsure.length ? ` (${v.unsure.join(', ')})` : ''}`);
    out.push(`- ${r.matrix.reason}`);
  }
  if (r.crashes.length) {
    out.push('', `### Crash reports (${r.crashes.length})`);
    for (const c of r.crashes.slice(0, 10)) out.push(`- ${c.log.fileName}: ${c.best.title} (${c.best.confidence})`);
  }
  out.push('', '_Generated by Smash Mod Doctor; runs locally, nothing uploaded._');
  return out.join('\n');
}
